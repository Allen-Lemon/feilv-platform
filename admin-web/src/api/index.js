import request from './request'

export const adminApi = {
  login: (data) => request.post('/v1/auth/admin-login', data),
  profile: (config) => request.post('/v1/auth/admin-profile', undefined, config),
  wechatSettings: () => request.get('/v1/admin/system/wechat', { silentError: true }),
  saveWechatLogin: (data) => request.put('/v1/admin/system/wechat/login', data, { silentError: true }),
  saveWechatPayment: (data) => request.put('/v1/admin/system/wechat/payment', data, { silentError: true }),
  validateWechat: (section) => request.post('/v1/admin/system/wechat/validate', { section }, { silentError: true }),
  stats: () => request.get('/v1/admin/stats'),
  customerUsers: (params) => request.get('/v1/admin/users', { params }),
  customerUser: (id) => request.get(`/v1/admin/users/${id}`),
  changeCustomerStatus: (id, status) => request.post(`/v1/admin/users/${id}/status`, { status }),
  orders: (params) => request.get('/v1/admin/orders', { params }),
  cancelOrder: (id, reason) => request.post(`/v1/admin/orders/${id}/cancel`, { reason }),
  completeOrder: (id, reason) => request.post(`/v1/admin/orders/${id}/complete`, { reason }),
  handleComplaint: (id, data) => request.post(`/v1/admin/complaints/${id}/handle`, data),
  riders: () => request.get('/v1/admin/riders'),
  settlements: () => request.get('/v1/admin/settlements'),
  wallets: (params) => request.get('/v1/admin/wallets', { params }),
  walletEntries: (userId, params) => request.get(`/v1/admin/wallets/${userId}/entries`, { params }),
  withdrawals: (params) => request.get('/v1/admin/withdrawals', { params }),
  reviewWithdrawal: (id, data) => request.post(`/v1/admin/withdrawals/${id}/review`, data),
  // 兼容旧调用 complaints('OPEN')；独立投诉页使用分页 / 订单筛选参数。
  complaints: (params = 'OPEN') => request.get('/v1/admin/complaints', { params: typeof params === 'string' ? { status: params } : params }),
  reviewComplaint: (id, data) => request.post(`/v1/admin/complaints/${id}/review`, data),
  taskTags: () => request.get('/v1/admin/task-tags'),
  createTaskTag: (data) => request.post('/v1/admin/task-tags', data),
  updateTaskTag: (id, data) => request.put(`/v1/admin/task-tags/${id}`, data),
  customTasks: (params) => request.get('/v1/admin/custom-tasks', { params }),
  customTask: (orderId) => request.get(`/v1/admin/custom-tasks/${orderId}`),
  quoteCustomTask: (data) => request.post('/v1/admin/custom-tasks/quote', data),
  createCustomTask: (data) => request.post('/v1/admin/custom-tasks', data),
  systemMenus: () => request.get('/v1/admin/system/menus'),
  saveMenu: (data) => request.post('/v1/admin/system/menus', data),
  deleteMenu: (id) => request.delete(`/v1/admin/system/menus/${id}`),
  systemRoles: () => request.get('/v1/admin/system/roles'),
  saveRole: (data) => request.post('/v1/admin/system/roles', data),
  assignRoleMenus: (roleId, menuIds) => request.post(`/v1/admin/system/roles/${roleId}/menus`, { menuIds }),
  systemUsers: () => request.get('/v1/admin/system/users'),
  changeUserStatus: (id, status) => request.post(`/v1/admin/system/users/${id}/status`, { status }),
  assignUserRoles: (id, roleIds) => request.post(`/v1/admin/system/users/${id}/roles`, { roleIds }),
  createAdmin: (data) => request.post('/v1/admin/system/users', data)
}
